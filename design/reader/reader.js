const root = document.documentElement;
const languageButtons = document.querySelectorAll("[data-language]");
const themeButton = document.querySelector(".theme-button");
const themeText = themeButton.querySelector("[data-copy]");
const contents = document.querySelector("#contents");

function setLanguage(language) {
  const selected = copy[language] ? language : "en";
  root.lang = selected;
  document.querySelectorAll("[data-copy]").forEach((element) => {
    const value = copy[selected][element.dataset.copy];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelector(".language-switch").setAttribute("aria-label", copy[selected]["language-label"]);
  document.querySelector(".theme-button").setAttribute("aria-label", copy[selected]["theme-label"]);
  document.querySelector(".site-header .book-context").setAttribute("aria-label", copy[selected]["book-label"]);
  document.querySelector(".shelf-link").setAttribute("aria-label", copy[selected]["shelf-aria"]);
  document.querySelector(".table-scroll").setAttribute("aria-label", copy[selected]["comparison-label"]);
  document.querySelector(".equation").setAttribute("aria-label", copy[selected]["equation-aria"]);
  languageButtons.forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.language === selected)));
  themeText.textContent = root.dataset.theme === "dark" ? copy[selected]["light-mode"] : copy[selected]["dark-mode"];
}

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.language)));

themeButton.addEventListener("click", () => {
  const dark = root.dataset.theme !== "dark";
  root.dataset.theme = dark ? "dark" : "light";
  themeButton.setAttribute("aria-pressed", String(dark));
  themeText.textContent = dark ? copy[root.lang]["light-mode"] : copy[root.lang]["dark-mode"];
  try { localStorage.setItem("reader-specimen-theme", root.dataset.theme); } catch { /* Storage may be unavailable for local files. */ }
});

try {
  const savedTheme = localStorage.getItem("reader-specimen-theme");
  if (savedTheme === "dark" || savedTheme === "light") root.dataset.theme = savedTheme;
} catch { /* The control still works when storage is unavailable. */ }
themeButton.setAttribute("aria-pressed", String(root.dataset.theme === "dark"));

const mobileContents = window.matchMedia("(max-width: 800px)");
contents.open = !mobileContents.matches;
mobileContents.addEventListener?.("change", (event) => { contents.open = !event.matches; });

document.querySelectorAll(".contents a").forEach((link) => {
  link.addEventListener("click", () => {
    if (mobileContents.matches) contents.open = false;
  });
});

const sections = [...document.querySelectorAll(".chapter-section")];
const linksById = new Map([...document.querySelectorAll(".contents a")].map((link) => [link.hash.slice(1), link]));
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      linksById.forEach((link) => link.removeAttribute("aria-current"));
      linksById.get(entry.target.id)?.setAttribute("aria-current", "location");
    });
  }, { rootMargin: "-15% 0px -70% 0px" });
  sections.forEach((section) => observer.observe(section));
}

setLanguage(root.lang);
